// Runs the parser cases through the offline parser and, when a key is set,
// through the real AI parser, then writes docs/PARSER_EVAL.md.
// Never part of `npm run verify`: it spends real API calls. Run: npm run eval:parser
import { existsSync, writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { handleParse } from '../../api/parse';
import { loadConfig } from '../../api/_lib/config';
import { parseOffline } from '../../src/parser';
import type { ParseResult } from '../../src/parser';
import { fromAiResponse } from '../../src/parser/ai';
import blindJson from '../fixtures/parser-blind.json';
import holdoutJson from '../fixtures/parser-holdout.json';
import { PARSER_CASES, differences } from '../fixtures/parserMatch';
import type { ParserCase } from '../fixtures/parserMatch';

const HOLDOUT = holdoutJson as ParserCase[];
const BLIND = blindJson as ParserCase[];
const say = (line: string) => process.stdout.write(`${line}\n`);

async function aiParse(text: string): Promise<{ result: ParseResult; ms: number } | { error: string; ms: number }> {
  const started = performance.now();
  const response = await handleParse(
    new Request('http://eval.local/api/parse', { method: 'POST', body: JSON.stringify({ text, locale: 'en' }) }),
    { config: loadConfig(process.env), fetch, limiter: { allow: () => true } },
  );
  const ms = Math.round(performance.now() - started);
  const body: unknown = await response.json();
  if (!response.ok) return { error: String((body as { error?: string }).error ?? response.status), ms };
  const result = fromAiResponse(text, body);
  return result ? { result, ms } : { error: 'invalid answer', ms };
}

it('parser evaluation', async () => {
  if (existsSync('.env')) process.loadEnvFile('.env');
  const live = Boolean(process.env.NVIDIA_API_KEY);
  if (!live) say('NVIDIA_API_KEY is not set: only the offline parser is evaluated, and docs/PARSER_EVAL.md is not rewritten.');
  const model = loadConfig(process.env).model;

  const rows: string[] = [];
  const tally = {
    tuning: { total: 0, offline: 0, ai: 0 },
    holdout: { total: 0, offline: 0, ai: 0 },
    blind: { total: 0, offline: 0, ai: 0 },
  };
  for (const [set, cases] of [['tuning', PARSER_CASES], ['holdout', HOLDOUT], ['blind', BLIND]] as const) {
    for (const testCase of cases) {
      const offline = differences(parseOffline(testCase.text), testCase.expect);
      let aiCell = 'not run';
      if (live) {
        const ai = await aiParse(testCase.text);
        if ('error' in ai) aiCell = `error: ${ai.error} (${ai.ms} ms)`;
        else {
          const problems = differences(ai.result, testCase.expect);
          if (problems.length === 0) tally[set].ai += 1;
          aiCell = problems.length === 0 ? `pass (${ai.ms} ms)` : `fail: ${problems[0]}`;
        }
      }
      tally[set].total += 1;
      if (offline.length === 0) tally[set].offline += 1;
      rows.push(`| ${set} | ${testCase.id} | ${offline.length === 0 ? 'pass' : `fail: ${offline[0]}`} | ${aiCell.replaceAll('|', '/')} |`);
    }
  }
  const { tuning, holdout, blind } = tally;
  say(`offline: tuning ${tuning.offline}/${tuning.total}, held out ${holdout.offline}/${holdout.total}, blind ${blind.offline}/${blind.total}`);
  if (live) say(`AI (${model}): tuning ${tuning.ai}/${tuning.total}, held out ${holdout.ai}/${holdout.total}, blind ${blind.ai}/${blind.total}`);
  if (!live) return;

  writeFileSync(
    'docs/PARSER_EVAL.md',
    [
      '# Parser evaluation',
      '',
      `Generated by \`npm run eval:parser\` on ${new Date().toISOString().slice(0, 10)}. AI model: \`${model}\` through NVIDIA's hosted API, temperature 0, reasoning off.`,
      '',
      'Three sets, and only the last is a fair measure of both parsers:',
      '',
      '- **Tuning** (`tests/fixtures/parser-cases.json`): written while the offline parser was built. The AI prompt was revised after seeing its failures here.',
      '- **Held out, seen** (`tests/fixtures/parser-holdout.json`): written after the offline parser and never used to change it, but the AI failures on it were seen before the prompt was revised.',
      '- **Blind** (`tests/fixtures/parser-blind.json`): committed before the prompt was revised and never used to change either parser. Two of its cases are not in English, which the offline parser is not built to read.',
      '',
      '| Set | Offline | AI |',
      '| --- | --- | --- |',
      `| Tuning (${tuning.total}) | ${tuning.offline} pass | ${tuning.ai} pass |`,
      `| Held out, seen (${holdout.total}) | ${holdout.offline} pass | ${holdout.ai} pass |`,
      `| Blind (${blind.total}) | ${blind.offline} pass | ${blind.ai} pass |`,
      '',
      '| Set | Case | Offline | AI |',
      '| --- | --- | --- | --- |',
      ...rows,
      '',
    ].join('\n'),
  );
}, 600_000);
